#!/usr/bin/env python3
"""Keep the documentation pack consistent with docs/STATUS.json.

Two modes:

    python3 scripts/docs_sync.py            regenerate docs/PROGRESS.md
    python3 scripts/docs_sync.py --check    verify it is up to date, exit 1 if not

--check is what CI runs. It never writes, so a pull request that changes STATUS.json
without regenerating PROGRESS.md fails rather than silently drifting.

Also validates that every file referenced by docs/TRACEABILITY.md actually exists,
which is the cheapest available guard against documentation describing code that is
not there, and (since S10) two consistency guards:

  - every relative markdown link in docs/, the root *.md files, .agent/ and
    server/README.md points at a file that exists, so a folder can be removed
    without silently breaking the documents that pointed into it;
  - the retired brand colours (#0C447C navy, #5DCAA5 mint) appear nowhere in src/
    or docs/, except in docs/CHANGELOG.md and on a line that says "retired".
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parent.parent
STATUS = ROOT / "docs" / "STATUS.json"
PROGRESS = ROOT / "docs" / "PROGRESS.md"
TRACEABILITY = ROOT / "docs" / "TRACEABILITY.md"

MARK = {"done": "x", "partial": "~", "todo": " "}
ORDER = {"done": 0, "partial": 1, "todo": 2}
GENERATED = "<!-- GENERATED BY scripts/docs_sync.py — DO NOT EDIT BY HAND -->"


def load_status() -> dict:
    try:
        return json.loads(STATUS.read_text(encoding="utf-8"))
    except FileNotFoundError:
        sys.exit(f"error: {STATUS.relative_to(ROOT)} not found")
    except json.JSONDecodeError as exc:
        sys.exit(f"error: {STATUS.relative_to(ROOT)} is not valid JSON: {exc}")


def validate(status: dict) -> list[str]:
    """Structural checks on STATUS.json itself."""
    problems: list[str] = []
    allowed = set(status.get("status_values", ["done", "partial", "todo"]))
    seen_keys: set[str] = set()

    for module in status.get("modules", []):
        key = module.get("key")
        if not key:
            problems.append("a module has no 'key'")
            continue
        if key in seen_keys:
            problems.append(f"duplicate module key: {key}")
        seen_keys.add(key)
        if not module.get("title"):
            problems.append(f"{key}: no 'title'")
        if "milestone" not in module:
            problems.append(f"{key}: no 'milestone'")
        if not module.get("items"):
            problems.append(f"{key}: no items")
        for item in module.get("items", []):
            if not item.get("name"):
                problems.append(f"{key}: an item has no 'name'")
            state = item.get("status")
            if state not in allowed:
                problems.append(
                    f"{key}: item {item.get('name')!r} has status {state!r}, "
                    f"expected one of {sorted(allowed)}"
                )
    return problems


def counts(items: list[dict]) -> tuple[int, int, int]:
    done = sum(1 for i in items if i["status"] == "done")
    partial = sum(1 for i in items if i["status"] == "partial")
    todo = sum(1 for i in items if i["status"] == "todo")
    return done, partial, todo


def bar(done: int, partial: int, total: int, width: int = 24) -> str:
    """A text progress bar. Partial items count as half."""
    if total == 0:
        return "-" * width
    filled = round((done + partial * 0.5) / total * width)
    return "#" * filled + "." * (width - filled)


def render(status: dict) -> str:
    modules = status.get("modules", [])
    all_items = [i for m in modules for i in m["items"]]
    d, p, t = counts(all_items)
    total = len(all_items)

    out: list[str] = []
    out.append("# Progress")
    out.append("")
    out.append(GENERATED)
    out.append("")
    out.append(
        "Regenerate with `python3 scripts/docs_sync.py`. "
        "Edit `docs/STATUS.json` instead of this file."
    )
    out.append("")
    out.append(f"**Project:** {status.get('project', 'unknown')}  ")
    out.append(f"**Baseline:** {status.get('baseline_date', 'unknown')}")
    out.append("")
    out.append("## Overall")
    out.append("")
    out.append(f"`{bar(d, p, total)}`  {d} done · {p} partial · {t} to do · {total} tracked")
    out.append("")
    out.append("Partial items count as half. Legend: `[x]` done · `[~]` partial · `[ ]` to do.")
    out.append("")
    out.append("## By module")
    out.append("")
    out.append("| Module | Milestone | Progress | Done | Partial | To do |")
    out.append("|---|---|---|---|---|---|")
    for m in sorted(modules, key=lambda m: (m["milestone"], m["key"])):
        md, mp, mt = counts(m["items"])
        out.append(
            f"| {m['key']} — {m['title']} | {m['milestone']} | "
            f"`{bar(md, mp, len(m['items']), 12)}` | {md} | {mp} | {mt} |"
        )
    out.append("")
    out.append("## Detail")
    out.append("")
    for m in sorted(modules, key=lambda m: (m["milestone"], m["key"])):
        md, mp, mt = counts(m["items"])
        out.append(f"### {m['key']} — {m['title']}")
        out.append("")
        out.append(f"Milestone {m['milestone']} · {md} done, {mp} partial, {mt} to do")
        out.append("")
        for item in sorted(m["items"], key=lambda i: (ORDER[i["status"]], i["name"])):
            line = f"- [{MARK[item['status']]}] {item['name']}"
            if item.get("note"):
                line += f" — _{item['note']}_"
            out.append(line)
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def git_ignored(paths: list[str]) -> set[str]:
    """Which of these paths does git deliberately ignore?

    Some referenced files are absent by design rather than by mistake --
    server/config.php holds the live credentials and is gitignored, so a document
    that mentions it is correct, not stale. Asking git keeps that list accurate
    without maintaining an allowlist here.
    """
    if not paths:
        return set()
    try:
        result = subprocess.run(
            ["git", "check-ignore", "--stdin"],
            input="\n".join(paths),
            capture_output=True,
            text=True,
            cwd=ROOT,
            check=False,
        )
    except (OSError, ValueError):
        return set()  # no git available; fall back to checking everything
    return {line.strip() for line in result.stdout.splitlines() if line.strip()}


def check_traceability() -> list[str]:
    """Every `path/like/this` in TRACEABILITY.md that looks like a repo file must exist."""
    if not TRACEABILITY.exists():
        return [f"{TRACEABILITY.relative_to(ROOT)} not found"]

    text = TRACEABILITY.read_text(encoding="utf-8")
    # Backticked tokens that look like a repo path with a known source extension.
    pattern = re.compile(r"`([A-Za-z0-9_./-]+\.(?:php|ts|tsx|sql|json|py|yml|css|html))(?::\d+)?`")
    candidates = [m for m in sorted(set(pattern.findall(text))) if not m.startswith("docs/")]

    missing = [c for c in candidates if not (ROOT / c).exists()]
    ignored = git_ignored(missing)
    return [
        f"TRACEABILITY.md references a missing file: {c}"
        for c in missing
        if c not in ignored
    ]


# ---------------------------------------------------------------------------
# Links

LINK = re.compile(r"(?<!!)\[[^\]\n]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
FENCE = re.compile(r"^\s*(```|~~~)")
INLINE_CODE = re.compile(r"`[^`\n]*`")


def markdown_files(root: Path = ROOT) -> list[Path]:
    """The documents whose links are checked."""
    files = set((root / "docs").rglob("*.md")) if (root / "docs").exists() else set()
    files |= set(root.glob("*.md"))
    if (root / ".agent").exists():
        files |= set((root / ".agent").rglob("*.md"))
    if (root / "server" / "README.md").exists():
        files.add(root / "server" / "README.md")
    return sorted(files)


def link_targets(text: str) -> list[tuple[int, str]]:
    """(line number, target) for every inline markdown link outside code."""
    out: list[tuple[int, str]] = []
    in_fence = False
    for n, line in enumerate(text.splitlines(), start=1):
        if FENCE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        for m in LINK.finditer(INLINE_CODE.sub("", line)):
            out.append((n, m.group(1)))
    return out


def is_external(target: str) -> bool:
    return bool(re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I)) or target.startswith("//")


def check_links(root: Path = ROOT) -> list[str]:
    """Every relative link resolves to a file or folder in the repository.

    Skipped: external links (http:, mailto: and so on), links to a heading in the
    same file (#...), and site paths starting with / (routes of the app, not files).
    """
    problems: list[str] = []
    for path in markdown_files(root):
        text = path.read_text(encoding="utf-8")
        for line, target in link_targets(text):
            if is_external(target) or target.startswith("#") or target.startswith("/"):
                continue
            file_part = unquote(target.split("#", 1)[0].split("?", 1)[0])
            if not file_part:
                continue
            resolved = (path.parent / file_part).resolve()
            if not resolved.exists():
                problems.append(
                    f"{path.relative_to(root)}:{line}: broken link to {target}"
                )
    return problems


# ---------------------------------------------------------------------------
# Retired brand colours

RETIRED_COLOURS = re.compile(r"#(?:0C447C|5DCAA5)(?:[0-9a-f]{2})?\b", re.I)  # with or without alpha
# History, not guidance: the changelog, and the multi-tenant setup plan that was
# superseded before it was built (kept for the record, marked as such at its top).
COLOUR_ALLOWED_FILES = {"docs/CHANGELOG.md", "docs/RITAGREEN_SETUP.md"}
COLOUR_SUFFIXES = {".ts", ".tsx", ".js", ".jsx", ".css", ".html", ".json", ".svg", ".md", ".mjs"}


def check_retired_colours(root: Path = ROOT) -> list[str]:
    """The navy and mint of the old brand must not creep back in.

    A line that names them as retired is allowed, so the design system can say what
    they were; so is the changelog, which is history.
    """
    problems: list[str] = []
    for base in ("src", "docs"):
        folder = root / base
        if not folder.exists():
            continue
        for path in sorted(folder.rglob("*")):
            if not path.is_file() or path.suffix.lower() not in COLOUR_SUFFIXES:
                continue
            rel = path.relative_to(root).as_posix()
            if rel in COLOUR_ALLOWED_FILES:
                continue
            try:
                text = path.read_text(encoding="utf-8")
            except UnicodeDecodeError:
                continue
            for n, line in enumerate(text.splitlines(), start=1):
                if RETIRED_COLOURS.search(line) and "retired" not in line.lower():
                    problems.append(
                        f"{rel}:{n}: retired brand colour {RETIRED_COLOURS.search(line).group(0)}"
                        " (use the green tokens; say 'retired' on the line if it is history)"
                    )
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify PROGRESS.md is up to date without writing; exit 1 if not",
    )
    args = parser.parse_args()

    status = load_status()

    problems = validate(status)
    problems += check_traceability()
    problems += check_links()
    problems += check_retired_colours()
    if problems:
        print("Documentation consistency problems:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1

    rendered = render(status)

    if args.check:
        current = PROGRESS.read_text(encoding="utf-8") if PROGRESS.exists() else ""
        if current != rendered:
            print(
                "docs/PROGRESS.md is out of date with docs/STATUS.json.\n"
                "Run: python3 scripts/docs_sync.py",
                file=sys.stderr,
            )
            return 1
        print("docs are consistent")
        return 0

    PROGRESS.write_text(rendered, encoding="utf-8")
    print(f"wrote {PROGRESS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
